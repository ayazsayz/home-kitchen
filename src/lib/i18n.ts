const DICT: Record<Lang, Record<Key, string>> = { en, ar, ur };

export function t(lang: Lang, key: Key, vars?: Record<string, string | number>) {
  const s = DICT[lang]?.[key] ?? en[key];
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : s;
}

/** Translated text when available, otherwise the English original. */
export const localize = (base: string, i18n: I18nText | undefined, lang: Lang) => (lang !== "en" && i18n?.[lang]?.trim()) || base;
